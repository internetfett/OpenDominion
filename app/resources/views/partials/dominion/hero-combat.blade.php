Each turn you can choose from one of the five following actions:<br/>
<ul>
    <li>Attack: deals damage equal to your attack minus the opponent's defense</li>
    <li>Defend: doubles your defense this turn, but Defending two turns in a row leaves you Exposed (-5 defense before doubling). Used on an ally, you Guard them: +50% defense, and attacks aimed at them hit you instead</li>
    <li>Focus: increases your attack value for your next attack action. Used on an ally, you Rally them: their attack this turn gains your focus value</li>
    <li>Counter: if attacked this turn, performs a counter attack, even if an ally is guarding you</li>
    <li>Recover: heals you or an ally, but reduces your defense by 5 this turn. Each hero has 3 uses per battle</li>
</ul>
<p>Additionally, each combatant has a chance to evade incoming attacks, reducing the damage by half.</p>
<p>Attack and Defend can be used every turn, while each of the other actions can only be used every other turn.</p>
<p>All actions happen at the same time. Damage and healing land together before anyone falls, so a heal can save an ally from a killing blow.</p>
<p>When you run out of match time, your hero will take actions automatically using the selected strategy.</p>
<p>Heroes gain an additional 5 health with every level up and bring their combat loadout into every battle.</p>
